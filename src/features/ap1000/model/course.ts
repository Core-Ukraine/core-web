// A paragraph or several
const text = (...paragraphs: readonly string[]): Block => ({ kind: "text", paragraphs });

// A heading of a part of a module
const heading = (value: string): Block => ({ kind: "heading", text: value });

// A heading inside a part
const subheading = (value: string): Block => ({ kind: "subheading", text: value });

// The labels of a drawing as pairs of the label and its meaning
const glossary = (label: string, ...pairs: readonly (readonly [string, string])[]): Block => ({
  kind: "glossary",
  label,
  terms: pairs.map(([term, meaning]) => ({ term, meaning })),
});

