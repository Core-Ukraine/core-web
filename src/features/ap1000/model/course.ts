// A key for a block that stays the same between renders
export const blockKey = (block: Block): string => {
  switch (block.kind) {
    case "text":
      return `text:${block.paragraphs.join(" ")}`;
    case "points":
      return `points:${block.points.map((point) => point.lead).join(" ")}`;
    case "heading":
    case "subheading":
    case "part":
    case "note":
      return `${block.kind}:${block.text}`;
    case "drawing":
      return `drawing:${block.drawing}`;
    case "glossary":
    case "chain":
      return `${block.kind}:${block.label}`;
    case "parameters":
    case "cycle":
    case "positions":
    case "scenarios":
    case "timeline":
    case "counts":
    case "fleet":
    case "videos":
    case "sources":
    case "quiz":
      return block.kind;
  }
};
